BEGIN;

CREATE TABLE IF NOT EXISTS estado (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS municipio (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255) NOT NULL,
    estado_id integer NOT NULL REFERENCES estado(id),
    CONSTRAINT uk_municipio_estado_nombre UNIQUE (estado_id, nombre)
);

ALTER TABLE cliente ADD COLUMN IF NOT EXISTS municipio_id integer;

DO $$
BEGIN
    IF to_regclass('public.ubicacion') IS NOT NULL THEN
        INSERT INTO estado (nombre)
        SELECT DISTINCT COALESCE(NULLIF(BTRIM(estado), ''), 'Sin especificar')
        FROM ubicacion
        ON CONFLICT (nombre) DO NOTHING;

        INSERT INTO municipio (nombre, estado_id)
        SELECT DISTINCT
            COALESCE(NULLIF(BTRIM(u.ciudad), ''), 'Sin especificar'),
            e.id
        FROM ubicacion u
        JOIN estado e
          ON e.nombre = COALESCE(NULLIF(BTRIM(u.estado), ''), 'Sin especificar')
        ON CONFLICT (estado_id, nombre) DO NOTHING;

        UPDATE cliente c
        SET municipio_id = m.id
        FROM ubicacion u
        JOIN estado e
          ON e.nombre = COALESCE(NULLIF(BTRIM(u.estado), ''), 'Sin especificar')
        JOIN municipio m
          ON m.estado_id = e.id
         AND m.nombre = COALESCE(NULLIF(BTRIM(u.ciudad), ''), 'Sin especificar')
        WHERE c.ubicacion_id = u.id
          AND c.municipio_id IS NULL;
    END IF;
END
$$;

ALTER TABLE cliente DROP COLUMN IF EXISTS ubicacion_id;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'cliente'::regclass
          AND conname = 'fk_cliente_municipio'
    ) THEN
        ALTER TABLE cliente
            ADD CONSTRAINT fk_cliente_municipio
            FOREIGN KEY (municipio_id) REFERENCES municipio(id);
    END IF;
END
$$;

DROP TABLE IF EXISTS ubicacion;

COMMIT;
